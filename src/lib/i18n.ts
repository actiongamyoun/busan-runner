// 번역 함수 (hook 밖에서도 쓸 수 있게 lang 직접 전달)
export function t(key: string, lang: Lang = 'ko'): string {
  const dict = I18N[lang] || I18N.ko;
  const val = dict[key];
  if (val === undefined) return (I18N.ko[key] as string) || key;
  if (typeof val === 'string') return val;
  return String(val);
}

// 배열/함수 값을 가져올 때
export function ti(key: string, lang: Lang = 'ko'): any {
  const dict = I18N[lang] || I18N.ko;
  return dict[key];
}

// 가격 포맷 (언어별 locale)
export function formatPrice(n: number, lang: Lang = 'ko'): string {
  if (n === 0) return t('market.free', lang);
  const locale = lang === 'en' ? 'en-US' : 'ko-KR';
  return n.toLocaleString(locale) + t('market.currency.suffix', lang);
}

// 시간 표시
export function timeAgo(ts: string | number | Date, lang: Lang = 'ko'): string {
  const date = new Date(ts);
  const diff = Math.floor((Date.now() - date.getTime()) / 1000);
  if (diff < 60) return t('time.now', lang);
  if (diff < 3600) return `${Math.floor(diff / 60)}${t('time.min', lang)}`;
  if (diff < 86400) return `${Math.floor(diff / 3600)}${t('time.hour', lang)}`;
  const days = Math.floor(diff / 86400);
  if (days < 30) return `${days}${t('time.day', lang)}`;
  return `${Math.floor(days / 30)}${t('time.month', lang)}`;
}

// 모임 날짜 포맷 ("오늘 · 19:00" / "Today · 7:00 PM")
export function formatMeetDate(dateStr: string, timeStr: string, lang: Lang = 'ko'): string {
  const d = new Date(dateStr);
  const today = new Date(); today.setHours(0,0,0,0);
  const target = new Date(dateStr); target.setHours(0,0,0,0);
  const diff = Math.round((target.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));
  const dowArr = ti('dow', lang) as string[];
  let label;
  if (diff === 0) label = t('meet.today', lang);
  else if (diff === 1) label = t('meet.tomorrow', lang);
  else {
    if (lang === 'en') label = `${dowArr[d.getDay()]} ${d.getMonth()+1}/${d.getDate()}`;
    else label = `${d.getMonth()+1}/${d.getDate()}(${dowArr[d.getDay()]})`;
  }
  return `${label} · ${timeStr.slice(0, 5)}`;
}
